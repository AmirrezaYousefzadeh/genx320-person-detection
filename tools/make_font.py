"""Generate the bitmap fonts of the board GUI (firmware/App/font.c) from DejaVu Sans.

DejaVu Sans is under the Bitstream Vera licence (free to use and redistribute, see firmware/App/FONT-LICENSE).
Each font covers ASCII 32..126 as 1-bit-per-pixel glyphs, one row of ceil(width/8) bytes per pixel row.
Usage: make_font.py <out_dir>   (writes font.c and font.h; run from the repo root)
"""
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = [  # (C name, file, pixel size)
    ("font_tiny", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 11),
    ("font_small", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 15),
    ("font_large", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 22),
    ("font_huge", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 44),
    ("font_title", "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf", 14),  # panel title
    ("font_label", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 10),  # small capital labels, box tags
]
FIRST, LAST = 32, 126


def render(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, bitmap = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = math.ceil(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = max(x1 - x0, 0), max(y1 - y0, 0)
        if w and h:
            img = Image.new("1", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=1)
            px = img.load()
            offset = len(bitmap)
            stride = (w + 7) // 8
            for y in range(h):
                row = 0
                for x in range(w):
                    if px[x, y]:
                        row |= 0x80 >> (x % 8) << (8 * (stride - 1 - x // 8))
                bitmap += row.to_bytes(stride, "big")
        else:
            offset = len(bitmap)
        glyphs.append((w, h, x0, y0, advance, offset))
    return height, ascent, glyphs, bytes(bitmap)


def emit(name, height, ascent, glyphs, bitmap):
    lines = [f"static const uint8_t {name}_bitmap[] = {{"]
    for i in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const font_glyph_t {name}_glyphs[] = {{")
    for (w, h, x0, y0, adv, off), code in zip(glyphs, range(FIRST, LAST + 1)):
        lines.append(f"    {{{w:2d}, {h:2d}, {x0:2d}, {y0:2d}, {adv:2d}, {off:5d}}}, /* '{chr(code)}' */"
                     .replace("'\\'", "'\\\\'"))
    lines.append("};")
    lines.append(f"const font_t {name} = {{{height}, {ascent}, {FIRST}, {LAST}, {name}_glyphs, {name}_bitmap}};")
    return "\n".join(lines)


def main(out_dir):
    out = Path(out_dir)
    body = ["/* Generated by tools/make_font.py from DejaVu Sans (Bitstream Vera licence, FONT-LICENSE). Do not edit. */",
            '#include "font.h"', ""]
    for name, path, size in FONTS:
        body.append(emit(name, *render(path, size)))
        body.append("")
    (out / "font.c").write_text("\n".join(body))
    (out / "font.h").write_text(f"""/* Bitmap fonts of the board GUI, generated by tools/make_font.py (see font.c). */
#ifndef FONT_H
#define FONT_H

#include <stdint.h>

typedef struct {{
  uint8_t width, height;   /* of the glyph bitmap */
  int8_t x_off, y_off;     /* of the bitmap from the pen position (y from the top of the line) */
  uint8_t advance;         /* pen advance in pixels */
  uint16_t bitmap_offset;  /* into font_t::bitmap, rows of ceil(width/8) bytes, MSB first */
}} font_glyph_t;

typedef struct {{
  uint8_t height, ascent;  /* line height and baseline from the top of the line */
  uint8_t first, last;     /* character codes covered */
  const font_glyph_t *glyphs;
  const uint8_t *bitmap;
}} font_t;

{chr(10).join(f"extern const font_t {name};  /* DejaVu Sans{' Bold' if 'Bold' in path else ''} {size} px */" for name, path, size in FONTS)}

#endif
""")
    print(f"wrote {out / 'font.c'} and font.h")


if __name__ == "__main__":
    main(sys.argv[1])
