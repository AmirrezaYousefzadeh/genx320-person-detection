"""Write the weights of a counting head (count_head.py, head_<pass>.json) as a C header for the firmware
(firmware/App/count_head.c): standardisation of the detector's output grid, then 1x1 conv 30->16 ReLU, 3x3 conv
16->16 ReLU (zero padding), 1x1 conv 16->1 softplus, summed over the 12x12 cells.
Usage: count_head_c.py work/count/heads_v4/head_fused.json firmware/App/count_head_weights.h
"""
import json
import sys

import numpy as np


def nested(a):
    if a.ndim == 1:
        return "{" + ", ".join(f"{v:.7g}f" for v in a) + "}"
    return "{" + ", ".join(nested(x) for x in a) + "}"


def arr(name, a):
    a = np.asarray(a, np.float32)
    dims = "".join(f"[{d}]" for d in a.shape)
    return f"static const float {name}{dims} = {nested(a)};\n"


def main(src, dst):
    m = json.load(open(src))
    w = [np.array(x, np.float32) for x in m["weights"]]
    k1, b1, k2, b2, k3, b3 = w  # Keras: kernels (kh, kw, in, out)
    s = m["scores"]
    out = (f"/* Counting head weights, generated by tools/count_head_c.py from {src}\n"
           f"   validation: exact {s['exact']}, MAE {s['mae']}, per true count {s['per_class']} */\n"
           "#define CH_IN 30\n#define CH_H 16\n"
           + arr("CH_MU", m["mean"]) + arr("CH_SD", m["std"])
           + arr("CH_W1", k1[0, 0]) + arr("CH_B1", b1)       # [in][out]
           + arr("CH_W2", k2) + arr("CH_B2", b2)             # [ky][kx][in][out]
           + arr("CH_W3", k3[0, 0, :, 0]) + arr("CH_B3", b3))
    open(dst, "w").write(out)
    print(f"wrote {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
